import Foundation

/// Когда список сам подкручивается к курсору — и когда не смеет.
///
/// Краткий вид и эскизы тянули прокрутку к курсору на КАЖДОМ обновлении вида. А обновление
/// приходит и само по себе: правило «гаснущая свежесть» просит перекрасить имена — при
/// пятиминутном сроке раз в пятнадцать секунд. Человек листал список вниз, курсор оставался
/// на «..» в начале — и ровно через пятнадцать секунд список прыгал обратно к курсору.
/// В подробном виде такого не было: там за курсором идут только по событию.
///
/// Теперь так везде: за курсором идут, когда он переехал или сменилась папка. Если идти
/// некуда — список ещё пуст, а так бывает: номер курсора при открытии папки приходит раньше
/// самих файлов, — просьба запоминается и исполняется, когда файлы придут.
struct CursorFollow {

    /// Просьба, которую ещё не исполнили.
    private(set) var pending = false

    /// - Parameters:
    ///   - wanted: курсор переехал или сменилась папка.
    ///   - canScroll: список уже знает этот номер.
    /// - Returns: прокручивать ли к курсору сейчас.
    mutating func step(wanted: Bool, canScroll: Bool) -> Bool {
        if wanted { pending = true }
        guard pending, canScroll else { return false }
        pending = false
        return true
    }
}
